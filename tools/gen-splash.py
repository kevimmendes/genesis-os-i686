#!/usr/bin/env python3
"""Project Genesis - turn the boot-splash art into C source.

The art in tools/splash-ascii.txt is 80 characters wide and 48 lines tall,
because that is how it was drawn for a tall terminal. The reference machine
shows 80x25 characters, so the picture is merged two lines into one: every
character is ranked by how much ink it carries, each vertical pair is
averaged, and the result is mapped back to the nearest character of the same
ramp. The whole picture survives; nothing is cropped.

Run it with `make splash` after editing tools/splash-ascii.txt. The generated
file is checked in, so building the kernel does not need Python.
"""

import os
import sys

RAMP = " .:-=+*#%@"          # lightest to darkest
COLUMNS = 80
SOURCE_ROWS = 48
MERGED_ROWS = SOURCE_ROWS // 2

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "splash-ascii.txt")
OUTPUT = os.path.join(HERE, os.pardir, "kernel", "arch", "i686", "splash_art.c")


def density(glyph):
    """Ink carried by one art character, 0 (blank) .. 9 (solid)."""
    return RAMP.index(glyph) if glyph in RAMP else 0


def read_art():
    with open(SOURCE, encoding="ascii") as handle:
        lines = [line.rstrip("\n") for line in handle if line.strip()]

    if len(lines) < SOURCE_ROWS:
        sys.exit(f"error: {SOURCE} has {len(lines)} lines, expected {SOURCE_ROWS}")

    art = []
    for index, line in enumerate(lines[:SOURCE_ROWS]):
        if len(line) > COLUMNS:
            line = line[:COLUMNS]
        elif len(line) < COLUMNS:
            # The art is a picture: a short line keeps its own edge character.
            line += line[-1] * (COLUMNS - len(line))
        art.append(line)
        if len(set(line) - set(RAMP)):
            sys.exit(f"error: line {index + 1} uses characters outside '{RAMP}'")
    return art


def merge(art):
    merged = []
    for row in range(MERGED_ROWS):
        upper, lower = art[2 * row], art[2 * row + 1]
        merged.append(
            "".join(
                RAMP[(density(upper[column]) + density(lower[column]) + 1) // 2]
                for column in range(COLUMNS)
            )
        )
    return merged


def main():
    rows = merge(read_art())

    body = "\n".join(f'    "{row}",' for row in rows)
    source = f"""/*
 * Project Genesis - boot splash art.
 *
 * Generated by tools/gen-splash.py from tools/splash-ascii.txt: the original
 * 80x48 drawing merged into the 24 lines of an 80x25 VGA text screen. Do not
 * edit this file by hand - edit the text file and run `make splash`.
 */

#include <arch/i686/splash.h>

const char splash_art[SPLASH_ART_ROWS][SPLASH_ART_COLUMNS + 1] = {{
{body}
}};
"""

    with open(OUTPUT, "w", encoding="ascii") as handle:
        handle.write(source)

    print(f"wrote {os.path.relpath(OUTPUT)} ({MERGED_ROWS} rows of {COLUMNS})")


if __name__ == "__main__":
    main()
